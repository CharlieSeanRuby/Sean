    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String username = Username.getText().trim();
        String password = Password.getText();
        String Passwordd = Password2.getText();
        String type = accountType.getSelectedItem().toString();
        
        if(username.isEmpty() || password.isEmpty() || Passwordd.isEmpty()){
            JOptionPane.showMessageDialog(this, "Please fill in all fields.");
            return;
        }
        if(!password.equals(Passwordd)){
             JOptionPane.showMessageDialog(this, "Password do not match.");
             return;
        }
        boolean registered = AccountManager.registerAccount(username, password, type);
        
        if (registered){
             JOptionPane.showMessageDialog(this, "Account Created Successfully!");
             Username.setText("");
             Password.setText("");
             Password2.setText("");
        }else{
            JOptionPane.showMessageDialog(this, "Account coulf not be created, Username may be already Exist.");
        }
        Main f = new Main();
        f.show();
        this.dispose();
       
    }//GEN-LAST:event_jButton1ActionPerformed

